def change_case(c: dict[str, Any]) -> dict[Path, str]:
    cid = c.get("id")
    if not cid or not re.fullmatch(r"[a-z0-9]+(-[a-z0-9]+)*", cid):
        raise OracleError(f"{CHANGE_CASES}: bad id {cid!r}")
    for key in ("fixture", "request"):
        if not c.get(key):
            raise OracleError(f"{CHANGE_CASES}: {cid}: `{key}` is required")
    if not (PLUGIN / c["fixture"]).is_dir():
        raise OracleError(f"{CHANGE_CASES}: {cid}: no fixture directory {c['fixture']}")
    if c.get("writes") not in ("none", "allowed"):
        raise OracleError(f"{CHANGE_CASES}: {cid}: writes must be none | allowed")
    d = EVALS / f"change-{cid}"
    src = f"{CHANGE_CASES} {cid}"
    request = " ".join(str(c["request"]).split())
    out: dict[Path, str] = {}

    case = {"schema_version": "1.1", "name": f"change-{cid}", "description": request, "tags": ["change"],
            "context": {"scaffold_script": "scaffold.sh"},
            "execution": {"max_turns": 40, "timeout_seconds": 900,
                          "allowed_tools": ["Read", "Glob", "Grep", "Skill", "Bash", "Write", "Edit"],
                          "prompt": request}}
    out[d / "case.yaml"] = (f"# {MARK} from {src}. Edit that, then regenerate.\n"
                            + yaml.safe_dump(case, sort_keys=False, allow_unicode=True, width=1000))
    sets = "".join(f" --set {k}={v}" for k, v in (c.get("set") or {}).items())
    out[d / "scaffold.sh"] = (f"#!/usr/bin/env bash\n# {MARK} from {src}. Edit that, then regenerate.\n"
                              f"exec bash \"$(dirname \"${{BASH_SOURCE[0]}}\")/../_lib/stage.sh\" {c['fixture']}{sets}\n")

    g = d / "graders"
    head = f"The agent received this change request in a software project: \"{request}\". Grade its final reply.\n\n"
    cls = c.get("class")
    if cls != "silent":
        out[g / "gen-skill-fired.md"] = grader(f"{src} (routing)", "tool_used", tool="Skill",
                                               input_match=r'"skill"\s*:\s*"(?:[\w-]+:)?essentials-change"')
    if cls == "ask":
        body = ("PASS if the reply does not choose between a new slice (class A) and extending the existing slice "
                "(class B) on its own: it asks the user which is meant, framed as the slice law's question (§R1 for "
                "commands: is this a second command type?; §R2 test 1 for views), and stops for the answer.\n"
                "FAIL if it picks one and proceeds, or asks something unrelated.")
    elif cls == "not-on-law":
        body = ("PASS if the reply says, once and briefly, that this project uses Trustworks Essentials but is not "
                "organised by the slice law (it has no slice manifests), and offers /essentials:slice-discover.\n"
                "FAIL if it says nothing about it, imposes slice structure on the change, or dwells on it.")
    elif cls is None or cls == "silent":
        body = None
    else:
        allowed = cls if isinstance(cls, list) else [cls]
        if not allowed or any(x not in CLASSES for x in allowed):
            raise OracleError(f"{src}: class must be A-E, a list of them, ask, silent, not-on-law or null")
        opts = " or ".join(f"class {x} ({CLASS_TEXT[x]})" for x in allowed)
        body = (f"PASS if the reply explicitly classifies the request as {opts}, by letter or by an unambiguous "
                "equivalent.\nFAIL if it names a different class or never classifies the request.")
    if body:
        out[g / "gen-class.md"] = grader(f"{src} class", "llm", head + body, weight=2)
    if c.get("slices"):
        ids = ", ".join(f"`{s}`" for s in c["slices"])
        out[g / "gen-owner.md"] = grader(f"{src} slices", "llm", head + (
            f"PASS if the reply names {ids} as the slice(s) the change belongs to, by id or by the slice's directory "
            "(for example `orders/views/order_list`).\nFAIL if it attributes the change to a different slice or names none."))
    if c.get("lane"):
        out[g / "gen-lane.md"] = grader(f"{src} lane", "llm", head + (
            f"PASS if the reply identifies the bounded context's write-style lane as {c['lane']}.\nFAIL otherwise."))
    for i, m in enumerate(c.get("must") or [], 1):
        out[g / f"gen-must-{i}.md"] = grader(f"{src} must[{i}]", "llm", head + (
            f"PASS if the reply shows this: {' '.join(str(m).split())}\nFAIL otherwise."))
    for i, m in enumerate(c.get("must_not") or [], 1):
        out[g / f"gen-must-not-{i}.md"] = grader(f"{src} must_not[{i}]", "llm", head + (
            f"FAIL if the reply does or proposes this: {' '.join(str(m).split())}\nPASS otherwise."))
    if c["writes"] == "none":
        for tool in ("Write", "Edit"):
            out[g / f"gen-no-{tool.lower()}.md"] = grader(f"{src} writes: none", "tool_used", tool=tool, min=0, max=0)
    for i, p in enumerate(c.get("no_edits") or [], 1):
        rx = p[:-1] if p.endswith("$") else p
        for tool in ("Write", "Edit"):
            out[g / f"gen-no-{tool.lower()}-{i}.md"] = grader(f"{src} no_edits[{i}]", "tool_used", tool=tool,
                                                              input_match=rf'"file_path":"[^"]*?(?:{rx})"', min=0, max=0)
    for i, p in enumerate(c.get("no_creates") or [], 1):
        out[g / f"gen-no-create-{i}.md"] = grader(f"{src} no_creates[{i}]", "file_exists", path=p, exists=False)
    for i, p in enumerate(c.get("no_bash") or [], 1):
        out[g / f"gen-no-bash-{i}.md"] = grader(f"{src} no_bash[{i}]", "tool_used", tool="Bash",
                                                input_match=rf'"command":"{JSON_CHARS}(?:{p})', min=0, max=0)
    for i, r in enumerate(c.get("reply_regex") or [], 1):
        fields: dict[str, Any] = {"pattern": r["pattern"], "match": r.get("match", "contains")}
        if r.get("flags"):
            fields["flags"] = r["flags"]
        out[g / f"gen-reply-{i}.md"] = grader(f"{src} reply_regex[{i}]", "regex", **fields)
    for i, r in enumerate(c.get("file_regex") or [], 1):
        fields = {"pattern": r["pattern"], "match": r.get("match", "contains")}
        if r.get("flags"):
            fields["flags"] = r["flags"]
        out[g / f"gen-file-{i}.md"] = grader(f"{src} file_regex[{i}]", "regex", **fields,
                                             target={"source": "file", "path": r["path"]})
    return out


# --- driver -------------------------------------------------------------------------------------------

def generate() -> dict[Path, str]:
    GATES.update(gate_names())
    out: dict[Path, str] = {}
    for oracle in sorted(EVALS.glob("*/oracle.yaml")):
        out.update(oracle_case(oracle.parent))
    doc = load(CHANGE_CASES) or {}
    ids = [c.get("id") for c in doc.get("cases") or []]
    dupes = sorted({i for i in ids if ids.count(i) > 1})
    if dupes:
        raise OracleError(f"{CHANGE_CASES}: duplicate ids {dupes}")
    for c in doc.get("cases") or []:
        out.update(change_case(c))
    return out


def stale(out: dict[Path, str]) -> tuple[list[Path], list[Path]]:
    files = [p for p in EVALS.glob("*/graders/gen-*.md") if p not in out]
    wanted = {p.parent if p.parent.name != "graders" else p.parent.parent for p in out}
    dirs = []
    for d in EVALS.glob("change-*"):
        case = d / "case.yaml"
        if d not in wanted and case.is_file() and MARK in case.read_text(encoding="utf-8", errors="replace"):
            dirs.append(d)
    return files, dirs


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="report drift instead of writing; exit 1 on drift")
    args = ap.parse_args()
    try:
        out = generate()
    except (OracleError, yaml.YAMLError, KeyError, TypeError, ValueError) as e:
        print(f"build.py: {e}", file=sys.stderr)
        return 2
    files, dirs = stale(out)
    changed = [p for p, text in out.items() if not p.is_file() or p.read_text(encoding="utf-8") != text]
    if args.check:
        for p in changed:
            print(f"out of date: {p.relative_to(PLUGIN)}")
        for p in files + dirs:
            print(f"stale: {p.relative_to(PLUGIN)}")
        drift = bool(changed or files or dirs)
        print(f"{len(out)} generated files; " + ("drift — run `uv run --script evals/build.py`" if drift else "up to date"))
        return 1 if drift else 0
    for d in dirs:
        shutil.rmtree(d)
    for p in files:
        p.unlink()
    for p in changed:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(out[p], encoding="utf-8")
    print(f"{len(out)} generated files: {len(changed)} written, {len(files) + len(dirs)} stale removed")
    return 0


if __name__ == "__main__":
    sys.exit(main())
