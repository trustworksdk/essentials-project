"""Generate the eval suite's graders from the fixtures' oracles.

`claude plugin eval` has no custom-code graders: a grader sees the agent's final message, its trace, the
files it created or one workspace file, never a file outside the run. So the oracles cannot be read at
grading time. They are compiled into grader files here instead, and `--check` fails when a committed
grader no longer matches its oracle, which keeps one source of truth:

- every case directory holding an `oracle.yaml` gets `graders/gen-*.md` from the fixture's
  `expected.yaml` (format 1, `tests/fixtures/*/expected.yaml`). oracle.yaml keys: `expected` (path from the
  plugin root), `command`, `sections` (which expected.yaml sections become graders), optional `ess_ids`
  (all | deterministic | none: which must_find `ess` ids must appear verbatim), `read_only` (no Write/Edit
  call) and `runs_scripts` (plugin scripts some Bash call must run);
- every case in `tests/fixtures/change-router/cases.yaml` becomes a whole `evals/change-<id>/` directory.

Hand-written graders are any `graders/*.md` not starting with `gen-`; this script never touches them.

usage:
  uv run --script evals/build.py            write the generated files, delete stale ones
  uv run --script evals/build.py --check    exit 1 when a generated file is missing, stale or edited
exit: 0 ok | 1 --check found drift | 2 an oracle is malformed (nothing written)
"""

from __future__ import annotations

import argparse
import re
import shutil
import sys
from pathlib import Path
from typing import Any

import yaml

PLUGIN = Path(__file__).resolve().parent.parent
EVALS = PLUGIN / "evals"
CHANGE_CASES = "tests/fixtures/change-router/cases.yaml"
SLICE_CHECK = PLUGIN / "commands" / "slice-check.md"
GEN = "gen-"
JSON_CHARS = r'(?:[^"\\]|\\.)*?'  # any run of characters inside one JSON string, escapes included
MARK = "GENERATED by evals/build.py"
SEVERITIES = {"Blocking", "Should-fix", "Advisory", None}
CLASSES = {"A", "B", "C", "D", "E"}
CLASS_TEXT = {
    "A": "a new capability, so a new slice",
    "B": "an extension of one existing slice",
    "C": "a change spanning several slices, decomposed into per-slice changes",
    "D": "a read-model shape change of an existing view",
    "E": "not a slice change, done plainly with no slice machinery and no manifest edit",
}
SECTIONS = ("runs_expect", "lanes", "must_find", "must_not_find", "skipped", "dismissed", "not_run", "terrain",
            "contexts", "slices", "ladder", "slice_map")
NOT_A_FINDING = (
    "A mention that is not a finding does not fail this check: the file listed as passing, cited as evidence for "
    "a different finding, or named in a lane or inventory summary.")


class OracleError(Exception):
    pass


def load(rel: str) -> Any:
    path = PLUGIN / rel
    if not path.is_file():
        raise OracleError(f"{rel}: no such file")
    with path.open(encoding="utf-8") as f:
        return yaml.safe_load(f)


def gate_names() -> dict[str, str]:
    names: dict[str, str] = {}
    for line in SLICE_CHECK.read_text(encoding="utf-8").splitlines():
        m = re.match(r'\|\s*(?:<a id="[^"]*"></a>)?\s*(\d+)\s*\|\s*\*\*(.+?)\*\*', line)
        if m:
            names.setdefault(m.group(1), m.group(2))
    return names


GATES: dict[str, str] = {}


def gate_label(gate: Any) -> str:
    g = str(gate)
    m = re.match(r"\d+", g)
    name = GATES.get(m.group(0)) if m else None
    return f"gate {g} ({name})" if name else f"gate {g}"


def slug(text: str) -> str:
    s = re.sub(r"[^a-z0-9]+", "-", str(text).lower()).strip("-")
    if not s:
        raise OracleError(f"cannot make a file name from {text!r}")
    return s


def grader(source: str, kind: str, body: str | None = None, **fields: Any) -> str:
    front = yaml.safe_dump({"type": kind, **fields}, sort_keys=False, allow_unicode=True, width=1000)
    text = f"---\n# {MARK} from {source}. Edit that, then regenerate.\n{front}---\n"
    return text + ("\n" + body.strip() + "\n" if body else "")


def bullets(items: list[str]) -> str:
    return "\n".join(f"- {i}" for i in items)


def where(entry: dict[str, Any]) -> str:
    file = entry.get("file")
    if not file:
        return ""
    place = f"anywhere under `{file}`" if str(file).endswith("/") else f"`{file}`"
    if entry.get("symbol"):
        place += f" (symbol `{entry['symbol']}`)"
    return place


# --- oracle cases: expected.yaml sections -------------------------------------------------------------

def intro(command: str) -> str:
    return (f"The agent's final message is the report `{command}` printed for a test project. Paths in it are "
            "relative to the project root, and a report may cite a file by path, by `path:line`, or by its type "
            "or directory name.\n\n")


def sec_runs_expect(exp: dict[str, Any], o: dict[str, Any], src: str) -> dict[str, str]:
    runs = [r for r in exp.get("runs") or [] if r.get("command") == o["command"] and r.get("expect")]
    if not runs:
        raise OracleError(f"{src}: no runs[] entry for {o['command']} with an `expect`")
    body = intro(o["command"]) + f"PASS if the agent did this: {runs[0]['expect']}\nFAIL otherwise."
    return {"gen-expect.md": grader(f"{src} runs[{o['command']}].expect", "llm", body, weight=2)}


def sec_lanes(exp: dict[str, Any], o: dict[str, Any], src: str) -> dict[str, str]:
    lines = []
    first = False
    for bc, lane in (exp.get("lanes") or {}).items():
        declared = lane.get("declared") or {}
        conflicting = len(set(declared.values())) > 1
        if str(lane.get("verdict")).lower() == "blocking":
            if lane.get("detected") == "blocking":
                text = "Blocking: more than one write style in one bounded context, so no lane is picked"
            else:
                text = f"code lane {lane.get('detected')}, but Blocking because its manifests declare conflicting lanes"
        else:
            text = f"{lane.get('detected')}"
            if conflicting:
                text += " (its manifests disagree)"
        signals = "; ".join(f"{s.get('kind')} at `{s.get('file')}`" for s in lane.get("signals") or [])
        lines.append(f"`{bc}`: {text}" + (f" — signals: {signals}" if signals else ""))
        first = first or bool(lane.get("report_before_findings"))
    if not lines:
        raise OracleError(f"{src}: `lanes` is empty")
    body = (intro(o["command"]) + "PASS if the report states the write-style lane of each bounded context as below"
            + (", before its findings" if first else "") + ":\n" + bullets(lines)
            + "\nFAIL if a bounded context is missing, or its lane or verdict differs.")
    return {"gen-lanes.md": grader(f"{src} lanes", "llm", body)}


def sec_must_find(exp: dict[str, Any], o: dict[str, Any], src: str) -> dict[str, str]:
    out: dict[str, str] = {}
    ess_policy = o.get("ess_ids", "deterministic")
    if ess_policy not in ("all", "deterministic", "none"):
        raise OracleError(f"{src}: ess_ids must be all | deterministic | none")
    for e in exp.get("must_find") or []:
        eid = e.get("id")
        if not eid or not e.get("what"):
            raise OracleError(f"{src}: must_find entry without id/what: {e}")
        if e.get("severity") not in SEVERITIES:
            raise OracleError(f"{src}: {eid}: severity {e.get('severity')!r} is not Blocking | Should-fix | Advisory")
        req = []
        if e.get("file"):
            req.append(f"it concerns {where(e)}")
        if e.get("also_names"):
            req.append("it also cites " + ", ".join(f"`{n}`" for n in e["also_names"]))
        if e.get("gate") is not None:
            label = gate_label(e["gate"]) + (f", id {e['ess']}" if e.get("ess") else "")
            req.append(f"it is filed under {label}, or plainly describes that check")
        elif e.get("ess"):
            req.append(f"it carries the id {e['ess']}")
        elif e.get("law"):
            req.append(f"it rests on {e['law']} of the slice law")
        if e.get("kind"):
            req.append(f"it is a {e['kind']} finding")
        if e.get("severity"):
            req.append(f"its severity is {e['severity']}")
        if e.get("rank"):
            req.append(f"it is ranked #{e['rank']} among the report's structural findings")
        req.append(f"its substance: {' '.join(str(e['what']).split())}")
        body = intro(o["command"]) + "PASS if the report contains a finding that matches all of:\n" + bullets(req)
        if e.get("also_ids"):
            body += "\nThe finding may also name " + ", ".join(str(i) for i in e["also_ids"]) + " beside its id."
        if e.get("may_merge_with"):
            body += f"\nReporting it inside the finding for {e['may_merge_with']} counts, provided its substance is stated."
        body += ("\nFAIL if no finding matches" + (", or the matching one has a different severity" if e.get("severity") else "")
                 + ". Ignore formatting, ordering and other findings.")
        out[f"gen-find-{slug(eid)}.md"] = grader(f"{src} must_find {eid}", "llm", body)
        ess = e.get("ess")
        if ess and (ess_policy == "all" or (ess_policy == "deterministic" and e.get("deterministic"))):
            out[f"gen-ess-{slug(ess)}.md"] = grader(f"{src} must_find {eid}.ess", "regex",
                                                   pattern=rf"\b{re.escape(ess)}\b")
    return out


def sec_must_not_find(exp: dict[str, Any], o: dict[str, Any], src: str) -> dict[str, str]:
    out: dict[str, str] = {}
    tolerated = exp.get("tolerated") or []
    for e in exp.get("must_not_find") or []:
        eid = e.get("id")
        if not eid:
            raise OracleError(f"{src}: must_not_find entry without id: {e}")
        gates = [str(g) for g in e.get("not_gates") or ([] if e.get("not_ids") else ["*"])]
        kinds = [gate_label(g) for g in gates if g != "*"] + [f"id {i}" for i in e.get("not_ids") or []]
        under = "of any kind" if "*" in gates else "under " + " or ".join(kinds)
        subject = f" about {where(e)}" if e.get("file") else ""
        what = f", described as: {e['what']}" if e.get("what") else ""
        body = intro(o["command"]) + f"PASS unless the report raises a finding {under}{subject}{what}."
        if e.get("why"):
            body += f"\nWhy that would be wrong: {' '.join(str(e['why']).split())}"
        body += "\n" + NOT_A_FINDING
        file = str(e.get("file") or "")
        tol = [t for t in tolerated if file and (not t.get("file") or str(t["file"]).startswith(file) or file.startswith(str(t["file"])))]
        if tol:
            body += "\nThese are tolerated and do not fail this check either:\n" + bullets(
                [" ".join(str(t.get("what", "")).split()) for t in tol])
        body += "\nFAIL only if such a finding is present."
        out[f"gen-not-{slug(eid)}.md"] = grader(f"{src} must_not_find {eid}", "llm", body)
    return out


def sec_skipped(exp: dict[str, Any], o: dict[str, Any], src: str) -> dict[str, str]:
    items = []
    for s in exp.get("skipped") or []:
        scope = f" for bounded context `{s['bc']}`" if s.get("bc") else ""
        items.append(f"{gate_label(s['gate'])}{scope}: {s.get('why', '')}")
    if not items:
        raise OracleError(f"{src}: `skipped` is empty")
    body = (intro(o["command"]) + "PASS if the report names each of these gates as not run, skipped or out of scope "
            "(a 'gates not run' block or an equivalent statement), rather than omitting it or calling it a pass:\n"
            + bullets(items) + "\nFAIL if any of them is missing or reported as passed.")
    return {"gen-skipped.md": grader(f"{src} skipped", "llm", body)}


def sec_dismissed(exp: dict[str, Any], o: dict[str, Any], src: str) -> dict[str, str]:
    out: dict[str, str] = {}
    for e in exp.get("dismissed") or []:
        eid = e.get("id")
        if not eid:
            raise OracleError(f"{src}: dismissed entry without id: {e}")
        subject = (f"{e['ess']} " if e.get("ess") else "the candidate ") + (f"at {where(e)}" if e.get("file") else "")
        body = (intro(o["command"]) + f"PASS if the report lists {subject.strip()} as a dismissed candidate (under a "
                "'Dismissed candidates' heading or an equivalent statement) with a reason, and does not report it as a "
                f"finding.\nThe reason it is not a finding: {' '.join(str(e.get('why', '')).split())}\n"
                "FAIL if it is reported as a finding, or not mentioned at all.")
        out[f"gen-dismissed-{slug(eid)}.md"] = grader(f"{src} dismissed {eid}", "llm", body)
    return out


def sec_not_run(exp: dict[str, Any], o: dict[str, Any], src: str) -> dict[str, str]:
    out: dict[str, str] = {}
    if "not_run" in exp and not exp["not_run"]:
        body = (intro(o["command"]) + "PASS if the report carries a 'Not run' block (or an equivalent statement) saying "
                "that every check ran, and calls no check skipped.\nFAIL if the block is missing, or the report says a "
                "check did not run.")
        return {"gen-not-run.md": grader(f"{src} not_run (empty)", "llm", body)}
    for e in exp.get("not_run") or []:
        eid = e.get("id")
        if not eid or not e.get("checks"):
            raise OracleError(f"{src}: not_run entry without id/checks: {e}")
        body = (intro(o["command"]) + f"PASS if the report names {e['checks']} as not run (under a 'Not run' heading "
                f"or an equivalent statement).\nWhy: {' '.join(str(e.get('why', '')).split())}\n"
                "FAIL if the report omits it, calls those checks clean or passed, or reports findings from them anyway.")
        out[f"gen-not-run-{slug(eid)}.md"] = grader(f"{src} not_run {eid}", "llm", body)
    return out


def sec_terrain(exp: dict[str, Any], o: dict[str, Any], src: str) -> dict[str, str]:
    t = exp.get("terrain") or {}
    if not t:
        raise OracleError(f"{src}: `terrain` is empty")
    items = [f"build: {t.get('build')}, {t.get('modules')} module(s), language {t.get('language')}",
             "frameworks: " + ", ".join(t.get("frameworks") or [])]
    if t.get("essentials") is False:
        items.append("it does not claim the project uses Trustworks Essentials")
    if t.get("lane"):
        items.append(f"its write-style lane is reported as `{t['lane']}` — reporting the nearest lane as the actual lane fails")
    if t.get("redirect_to_slice_check") is False:
        items.append("it does not redirect to /essentials:slice-check")
    body = intro(o["command"]) + "PASS if the report's terrain pass says all of:\n" + bullets(items) + "\nFAIL otherwise."
    return {"gen-terrain.md": grader(f"{src} terrain", "llm", body)}


def sec_contexts(exp: dict[str, Any], o: dict[str, Any], src: str) -> dict[str, str]:
    c = exp.get("contexts") or {}
    if not c:
        raise OracleError(f"{src}: `contexts` is empty")
    items = [f"exactly {c.get('count')} candidate bounded contexts — not one per package or layer"]
    for name, cand in (c.get("candidates") or {}).items():
        line = f"`{name}` owning " + ", ".join(cand.get("owns") or [])
        ce = cand.get("counter_evidence")
        if ce:
            line += f"; its counter-evidence must be reported: {ce.get('what')} (`{ce.get('file')}`)"
        items.append(line)
    if c.get("confidence_at_most"):
        items.append(f"confidence no higher than {c['confidence_at_most']}")
    body = (intro(o["command"]) + "PASS if the report's bounded-context pass proposes (names may differ slightly):\n"
            + bullets(items) + "\nFAIL if the count differs, a context is missing, or the counter-evidence is absent.")
    return {"gen-contexts.md": grader(f"{src} contexts", "llm", body)}


def sec_slices(exp: dict[str, Any], o: dict[str, Any], src: str) -> dict[str, str]:
    s = exp.get("slices") or {}
    if not s:
        raise OracleError(f"{src}: `slices` is empty")
    listed = [f"{x['kind']} `{x['slice']}` (from `{x['file']}`)" + (f" — {x['also']}" if x.get("also") else "")
              for x in s.get("list") or []]
    body = (intro(o["command"]) + f"PASS if the report proposes exactly {s.get('count')} candidate slices "
            "(names may differ slightly), namely:\n" + bullets(listed))
    also = [f"{x['kind']} `{x['slice']}` (from `{x['file']}`)" for x in s.get("also") or []]
    if also:
        body += "\nIt may additionally list these outside the count, or not at all:\n" + bullets(also)
    if s.get("order_controller_splits_into"):
        body += f"\nOrderController must be shown splitting into {s['order_controller_splits_into']} slices."
    body += "\nFAIL if the count differs or a listed slice is missing or merged into another."
    return {"gen-slices.md": grader(f"{src} slices", "llm", body)}


def sec_ladder(exp: dict[str, Any], o: dict[str, Any], src: str) -> dict[str, str]:
    lad = exp.get("ladder") or {}
    if not lad:
        raise OracleError(f"{src}: `ladder` is empty")
    items = [f"{k.replace('_', ' ')}: {v}" for k, v in lad.items()]
    body = (intro(o["command"]) + "PASS if the report's migration ladder satisfies:\n" + bullets(items)
            + "\nFAIL otherwise.")
    return {"gen-ladder.md": grader(f"{src} ladder", "llm", body)}


def sec_slice_map(exp: dict[str, Any], o: dict[str, Any], src: str) -> dict[str, str]:
    m = exp.get("slice_map") or {}
    if not m:
        raise OracleError(f"{src}: `slice_map` is empty")
    out: dict[str, str] = {}
    head = intro(o["command"])
    edges = [f"{a} → {msg} → {b}" for a, msg, b in m.get("edges") or []]
    out["gen-map-edges.md"] = grader(f"{src} slice_map.edges", "llm", head + (
        f"The project has {m.get('slices')} slices. PASS if the map shows every one of these flows "
        "(slice → event or command → slice), in any notation, and no flow between slices that is not listed:\n"
        + bullets(edges) + "\nFAIL if one is missing or an unlisted flow is drawn."))
    cycles = [" → ".join(c) for c in m.get("cycles") or []]
    out["gen-map-cycles.md"] = grader(f"{src} slice_map.cycles", "llm", head + (
        ("PASS if the map points out this cycle:\n" + bullets(cycles)) if cycles else
        "PASS if the map reports no cycle between slices.") + "\nFAIL otherwise.")
    writers = [f"{agg}: " + ", ".join(ws) for agg, ws in (m.get("writers") or {}).items()]
    out["gen-map-writers.md"] = grader(f"{src} slice_map.writers", "llm", head + (
        "PASS if the map shows who writes each aggregate or entity, as:\n" + bullets(writers)
        + "\nFAIL if a writer is missing or an extra writer is shown."))
    endpoints = [f"{ep} → {sl}" for ep, sl in (m.get("endpoints") or {}).items()]
    out["gen-map-endpoints.md"] = grader(f"{src} slice_map.endpoints", "llm", head + (
        "PASS if the map's endpoint index maps each HTTP endpoint to its slice as:\n" + bullets(endpoints)
        + "\nA query discriminator may be written as `?status=` or as a params note. FAIL if one is missing or "
        "mapped to another slice."))
    dangling = m.get("dangling") or []
    out["gen-map-dangling.md"] = grader(f"{src} slice_map.dangling", "llm", head + (
        ("PASS if the map reports these dangling messages (published or dispatched, never consumed, or the "
         "reverse):\n" + bullets([str(d) for d in dangling])) if dangling else
        "PASS if the map reports no dangling message: nothing it lists as published or dispatched without a "
        "consumer, or consumed without a producer.") + "\nFAIL otherwise.")
    return out


RENDER = {name: globals()[f"sec_{name}"] for name in SECTIONS}


def oracle_case(case_dir: Path) -> dict[Path, str]:
    o = yaml.safe_load((case_dir / "oracle.yaml").read_text(encoding="utf-8")) or {}
    src = str(o.get("expected") or "")
    if not src or not o.get("command") or not o.get("sections"):
        raise OracleError(f"{case_dir.name}/oracle.yaml: needs expected, command and sections")
    exp = load(src)
    out: dict[Path, str] = {}
    for section in o["sections"]:
        if section not in RENDER:
            raise OracleError(f"{case_dir.name}/oracle.yaml: unknown section {section!r} (known: {', '.join(SECTIONS)})")
        for name, text in RENDER[section](exp, o, src).items():
            path = case_dir / "graders" / name
            if path in out:
                raise OracleError(f"{case_dir.name}: two graders named {name}")
            out[path] = text
    if o.get("read_only"):
        for tool in ("Write", "Edit"):
            out[case_dir / "graders" / f"gen-no-{tool.lower()}.md"] = grader(
                f"{case_dir.name}/oracle.yaml read_only", "tool_used", tool=tool, min=0, max=0)
    for script in o.get("runs_scripts") or []:
        out[case_dir / "graders" / f"gen-ran-{slug(script)}.md"] = grader(
            f"{case_dir.name}/oracle.yaml runs_scripts", "tool_used", tool="Bash",
            input_match=rf'"command":"{JSON_CHARS}{re.escape(script)}')
    return out


