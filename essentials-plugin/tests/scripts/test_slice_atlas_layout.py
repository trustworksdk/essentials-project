def overlaps(a, b):
    return a["x"] < b["x"] + b["w"] and b["x"] < a["x"] + a["w"] and a["y"] < b["y"] + b["h"] and b["y"] < a["y"] + a["h"]


def inside(a, b):
    return b["x"] <= a["x"] and b["y"] <= a["y"] and a["x"] + a["w"] <= b["x"] + b["w"] and a["y"] + a["h"] <= b["y"] + b["h"]


def check_geometry(test, layout, label):
    atlas = layout["atlas"]
    cards = {c["id"]: c for c in atlas["cards"]}
    test.assertEqual(len(cards), len(atlas["cards"]), f"{label}: duplicate card id")
    for e in atlas["edges"]:
        test.assertIn(e["from"], cards, f"{label}: edge from a missing card {e}")
        test.assertIn(e["to"], cards, f"{label}: edge to a missing card {e}")
        test.assertEqual(e["cross"], cards[e["from"]]["segment"] != cards[e["to"]]["segment"], f"{label}: {e}")
    segs = {s["id"]: s for s in atlas["segments"]}
    ctx = {c["id"]: c for c in atlas["contexts"]}
    by_seg = {}
    for c in atlas["cards"]:
        by_seg.setdefault(c["segment"], []).append(c)
        test.assertTrue(inside(c, segs[c["segment"]]), f"{label}: card {c['id']} outside its segment")
    for sid, cs in by_seg.items():
        for i, a in enumerate(cs):
            for b in cs[i + 1:]:
                test.assertFalse(overlaps(a, b), f"{label}: cards overlap in {sid}: {a['id']} / {b['id']}")
    for s in atlas["segments"]:
        test.assertTrue(inside(s, ctx[s["bc"]]), f"{label}: segment {s['id']} outside its context")
    ids = sorted(ctx)
    for i, a in enumerate(ids):
        test.assertTrue(inside(ctx[a], atlas["bounds"]), f"{label}: context {a} outside the bounds")
        for b in ids[i + 1:]:
            test.assertFalse(overlaps(ctx[a], ctx[b]), f"{label}: contexts {a} and {b} overlap")
    boxes = atlas["scenarioBoxes"]
    for b in boxes:
        test.assertTrue(inside(b, segs[b["segment"]]), f"{label}: scenario box of {b['slice']} outside its segment")
        # The page draws under every full column (scenario stacks, else the invariants box), so a
        # zero-height box would leave that drawing outside any reserved space.
        test.assertGreaterEqual(b["h"], L.NO_SCENARIO_H, f"{label}: scenario box of {b['slice']} reserves no room")
        for c in by_seg.get(b["segment"], []):
            test.assertFalse(overlaps(b, c), f"{label}: scenario box of {b['slice']} overlaps card {c['id']}")
    for i, a in enumerate(boxes):
        for b in boxes[i + 1:]:
            test.assertFalse(overlaps(a, b), f"{label}: scenario boxes of {a['slice']} and {b['slice']} overlap")
    full = sorted((s["id"], col["slice"]) for s in atlas["segments"] for col in s["columns"] if not col["portal"])
    test.assertEqual(full, sorted((b["segment"], b["slice"]) for b in boxes), f"{label}: one box per full column")
    for st in layout["metro"]["stations"]:
        test.assertTrue(0 <= st["x"] <= layout["metro"]["bounds"]["w"] and 0 <= st["y"] <= layout["metro"]["bounds"]["h"])
    nr, nc = len(layout["matrix"]["rows"]), len(layout["matrix"]["cols"])
    for cell in layout["matrix"]["cells"]:
        test.assertTrue(0 <= cell["r"] < nr and 0 <= cell["c"] < nc, f"{label}: matrix cell out of range {cell}")


def context_of(layout):
    seg_bc = {s["id"]: s["bc"] for s in layout["atlas"]["segments"]}
    return {c["id"]: (seg_bc[c["segment"]], c["x"], c["y"]) for c in layout["atlas"]["cards"]}


def moved_outside(before, after, bc):
    """Cards outside context bc whose position changed, and whether every such move is a rigid
    translation of its whole context by that context's own origin delta."""
    b, a = context_of(before), context_of(after)
    origin_b = {c["id"]: (c["x"], c["y"]) for c in before["atlas"]["contexts"]}
    origin_a = {c["id"]: (c["x"], c["y"]) for c in after["atlas"]["contexts"]}
    moved, rigid = [], True
    for cid, (cbc, x, y) in b.items():
        if cbc == bc:
            continue
        if cid not in a:
            moved.append(cid)
            rigid = False
            continue
        _, x2, y2 = a[cid]
        if (x, y) != (x2, y2):
            moved.append(cid)
            dx, dy = origin_a[cbc][0] - origin_b[cbc][0], origin_a[cbc][1] - origin_b[cbc][1]
            rigid = rigid and (x2 - x, y2 - y) == (dx, dy)
    return moved, rigid


def with_extra_view(data, bc):
    """data plus one view in context bc fed by an event that context publishes (or by nothing)."""
    slices = copy.deepcopy([s for s in data["slices"]])
    events = sorted(e for s in slices if s["bc"] == bc for e in s["publishes"])
    slices.append(row(f"{bc}.added_view", "view", owns=["AddedList"],
                      projections=[("AddedProjection", events[:1])], endpoints=[("GET", f"/api/{bc}/added")]))
    return atlas_data(slices)


def zoom_budget(layout):
    """Drawn elements per Atlas zoom level (design §10.1), everything in view: L0 contexts + bridges;
    L1 contexts + segments + links; L2 segments + cards + edges; L3 L2 + scenario boxes."""
    a = layout["atlas"]
    l2 = len(a["segments"]) + len(a["cards"]) + len(a["edges"])
    return {"L0": len(a["contexts"]) + len(a["bridges"]),
            "L1": len(a["contexts"]) + len(a["segments"]) + len(a["links"]),
            "L2": l2, "L3": l2 + len([b for b in a["scenarioBoxes"] if b["h"] > 0]),
            "metro": len(layout["metro"]["lines"]) + len(layout["metro"]["stations"]),
            "matrixCells": len(layout["matrix"]["cells"])}


