def row(sid, kind, **f):
    """A `slices[]` row as `slice-index.py map` emits it, plus the C2 `flows` / `scenarios` / `doc`."""
    bc, name = sid.split(".", 1)
    r = {"id": sid, "bc": bc, "name": name, "kind": kind, "status": "live", "owner": bc + "-team",
         "summary": None, "language": "java", "tier": "cqrs-es", "lane": "decider",
         "path": f"{bc}/{KIND_DIR[kind]}/{name}", "package": None, "files": [],
         "handles": [], "serves": [], "publishes": [], "consumes": [], "dispatches": [], "writes": [],
         "owns": [], "projections": [], "reads": [], "endpoints": [], "invariants": [],
         "externalSystem": None, "direction": None, "supersedes": None, "dependsOn": [], "tests": ["unit"],
         "flags": [], "flows": [], "scenarios": [], "doc": None}
    if kind == "view":
        r["readModels"] = []
    for k, v in f.items():
        if k == "endpoints":
            v = [{"method": m, "path": p, "auth": "user"} for m, p in v]
        elif k == "projections":
            v = [{"name": n, "from": fr} for n, fr in v]
        elif k == "reads":
            v = [{"name": n, "via": via, "external": False} for n, via in v]
        elif k == "scenarios":
            v = [scenario(f"scenario {i + 1}") for i in range(v)]
        r[k] = v
    return r


def scenario(name):
    return {"name": name, "given": [], "when": None, "then": {"kind": "nothing"}, "test": None,
            "testResolved": {"status": "not-checked", "path": None, "line": None}, "note": None}


def broken(rel):
    return {"id": rel, "bc": None, "name": rel.rsplit("/", 1)[1], "kind": None, "status": None, "owner": None,
            "summary": None, "language": None, "tier": None, "lane": None, "path": rel, "package": None,
            "files": [], "handles": [], "serves": [], "publishes": [], "consumes": [], "dispatches": [],
            "writes": [], "owns": [], "projections": [], "reads": [], "endpoints": [], "invariants": [],
            "externalSystem": None, "direction": None, "supersedes": None, "dependsOn": [], "tests": [],
            "flags": [{"level": "error", "text": "slice.yaml is not valid YAML (line 3)"}], "error": True,
            "flows": [], "scenarios": [], "doc": None}


def inbound(s):
    out = []
    for n in s["consumes"] + [n for p in s["projections"] for n in p["from"]]:
        if n not in out:
            out.append(n)
    return out


def guess_bc(s):
    parts = s["path"].split("/")
    return parts[0] if len(parts) > 2 else "?"


def derive_processes(slices):
    """Design §6, a stand-in for slice_atlas.py: declared flows; per-context closures from entry
    slices, stopping at the context boundary and at slices that declare a flow; `~unattached:<bc>`."""
    good = [s for s in slices if not s.get("error")]
    procs = {}

    def proc(pid, name, declared):
        return procs.setdefault(pid, {"id": pid, "name": name, "declared": declared,
                                      "color": zlib.crc32(pid.encode()) % 12, "bcs": [], "sliceIds": [],
                                      "entries": [], "links": []})

    for s in good:
        for f in s["flows"]:
            proc(f, f, True)["sliceIds"].append(s["id"])
    free = [s for s in good if not s["flows"]]

    def entry(s):
        return ((s["kind"] == "command" and s["endpoints"])
                or (s["kind"] == "translation" and s["direction"] in ("inbound", "both", None))
                or (s["kind"] == "automation" and s.get("schedule")))

    reached = set()
    for e in sorted((s for s in free if entry(s)), key=lambda s: s["id"]):
        members, todo = [e["id"]], [e]
        while todo:
            x = todo.pop(0)
            for y in free:
                if y["bc"] != x["bc"] or y["id"] in members:
                    continue
                if set(x["publishes"]) & set(inbound(y)) or set(x["dispatches"]) & set(y["handles"]):
                    members.append(y["id"])
                    todo.append(y)
        p = proc("~" + e["id"], e["name"].replace("_", " "), False)
        p["sliceIds"] = sorted(members)
        p["entries"] = [e["id"]]
        reached.update(members)
    for s in slices:
        if s.get("error") or (not s["flows"] and s["id"] not in reached):
            b = s["bc"] or guess_bc(s)
            proc(f"~unattached:{b}", f"unattached {b}", False)["sliceIds"].append(s["id"])
    by_id = {s["id"]: s for s in slices}
    for p in procs.values():
        p["sliceIds"] = sorted(set(p["sliceIds"]))
        p["bcs"] = sorted({by_id[i]["bc"] or guess_bc(by_id[i]) for i in p["sliceIds"]})
    return sorted(procs.values(), key=lambda p: (not p["declared"], p["id"]))


def atlas_data(slices, diff=None):
    """The C2 keys the layout reads, computed from the rows as slice-index.py map computes them."""
    good = [s for s in slices if not s.get("error")]
    events = {}
    for s in good:
        for e in s["publishes"]:
            events.setdefault(e, (set(), set()))[0].add(s["id"])
        for e in inbound(s):
            events.setdefault(e, (set(), set()))[1].add(s["id"])
    bc_of = {s["id"]: s["bc"] for s in good}
    flows = []
    for e, (pubs, subs) in events.items():
        bcs = {bc_of[i] for i in pubs | subs}
        flows.append({"event": e, "bc": min(bc_of[i] for i in pubs) if pubs else min(bc_of[i] for i in subs),
                      "from": sorted(pubs), "to": sorted(subs), "crossContext": len(bcs) > 1,
                      "dangling": not pubs and bool(subs)})
    flows.sort(key=lambda f: (not f["crossContext"], f["event"]))
    groups = {}
    for s in good:
        for kind, targets in (("aggregate", s["writes"]), ("read-model", s["owns"])):
            for t in targets:
                groups.setdefault((t, kind), []).append(s)
    writers = [{"target": t, "kind": k, "bcs": sorted({s["bc"] for s in ss}), "slices": sorted(s["id"] for s in ss),
                "flag": "crossBc" if len({s["bc"] for s in ss}) > 1 else None} for (t, k), ss in groups.items()]
    writers.sort(key=lambda w: (w["flag"] is None, w["target"], w["kind"]))
    home = {}
    for s in good:
        for t in s["writes"] + s["owns"]:
            home.setdefault(t, set()).add(s["bc"])
    cross = []
    for s in good:
        for r in s["reads"]:
            bcs = home.get(r["name"], set())
            if bcs and s["bc"] not in bcs:
                r["external"] = True
                cross += [{"from": s["id"], "toBc": b, "model": r["name"], "via": r["via"],
                           "declared": r["via"] is not None} for b in sorted(bcs)]
    cross.sort(key=lambda c: (c["from"], c["toBc"], c["model"]))
    return {"meta": {"atlasVersion": 1}, "slices": slices, "processes": derive_processes(slices),
            "messages": [], "flows": flows, "writers": writers, "crossReads": cross, "issues": [],
            "lineage": {"fields": {}, "technicalColumns": []}, "diff": diff}


