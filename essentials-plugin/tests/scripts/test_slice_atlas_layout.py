def estate(n=60):
    """A generated estate: n contexts of 4-14 slices, cross-context reactors, declared journeys over
    three contexts, translations both ways, schedules, scenarios, reads with and without `via`."""
    out = []
    for i in range(n):
        c = f"c{i:02d}"
        ncmd = 2 + i % 4
        journey = [f"j{i - i % 6:02d}"] if i % 6 in (0, 1, 2) else []
        for k in range(ncmd):
            out.append(row(f"{c}.do_{k}", "command", handles=[f"Do{i}x{k}"], publishes=[f"Done{i}x{k}"]
                           + ([f"Failed{i}x{k}"] if k == 1 else []), writes=[f"Agg{i}x{k % 2}"],
                           endpoints=[("POST", f"/api/{c}/{k}")] if k % 2 == 0 else [],
                           flows=journey if k == 0 else [], scenarios=k % 3))
        for k in range(1 + i % 3):
            src = [f"Done{i}x{j}" for j in range(k, ncmd, 2)]
            out.append(row(f"{c}.list_{k}", "view", owns=[f"List{i}x{k}"], projections=[(f"P{k}", src)],
                           endpoints=[("GET", f"/api/{c}/list/{k}")],
                           reads=[(f"List{(i + 1) % n}x0", "Reader" if i % 2 == 0 else None)] if i % 5 == 0 else [],
                           flows=journey + ([f"j{(i + 6 - i % 6) % n:02d}"] if k == 0 and i % 6 == 2 else [])))
        out.append(row(f"{c}.react", "automation", consumes=[f"Done{(i - 1) % n}x0"], dispatches=[f"Do{i}x1"],
                       flows=journey if i % 6 in (1, 2) else []))
        if i % 4 == 0:
            out.append(row(f"{c}.retry", "automation", consumes=[f"Failed{i}x1"], dispatches=[f"Do{i}x1"]))
        if i % 7 == 0:
            out.append(row(f"{c}.ingest", "translation", externalSystem=f"Ext{i}", direction="inbound",
                           dispatches=[f"Do{i}x0"]))
        if i % 11 == 0:
            out.append(row(f"{c}.export", "translation", externalSystem=f"Out{i}", direction="outbound",
                           consumes=[f"Done{i}x0"]))
        if i % 9 == 0:
            out.append(row(f"{c}.nightly", "automation", dispatches=[f"Do{i}x0"], schedule={"fixedDelay": "PT1H"}))
    return atlas_data(out)


