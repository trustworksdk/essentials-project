package dk.trustworks.essentials.components.foundation.postgresql;

import com.fasterxml.jackson.annotation.JsonProperty;
import dk.trustworks.essentials.components.foundation.json.*;
import dk.trustworks.essentials.components.foundation.postgresql.MultiTableChangeListenerIT.*;
import dk.trustworks.essentials.reactive.LocalEventBus;
import org.jdbi.v3.core.Jdbi;
import org.junit.jupiter.api.*;
import org.testcontainers.junit.jupiter.*;
import org.testcontainers.postgresql.PostgreSQLContainer;
import org.testcontainers.shaded.org.awaitility.Awaitility;
import tools.jackson.databind.JsonNode;

import java.time.Duration;
import java.util.*;
import java.util.concurrent.CopyOnWriteArrayList;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * Regression tests for the {@link MultiTableChangeListener} robustness fixes (LN-2 to LN-6, N-6, N-7), against a real
 * PostgreSQL.
 */
@Testcontainers
class MultiTableChangeListenerRobustnessIT {
    private static final String TABLE_1 = "table1";
    private static final String TABLE_2 = "table2";

    @Container
    private static final PostgreSQLContainer postgreSQLContainer = new PostgreSQLContainer("postgres:18.4")
            .withDatabaseName("listen-notify-db")
            .withUsername("test-user")
            .withPassword("secret-password");

    private Jdbi                                            jdbi;
    private JSONSerializer                                  jsonSerializer;
    private LocalEventBus                                   eventBus;
    private List<Object>                                    received;
    private MultiTableChangeListener<TestTableNotification> listener;

    @BeforeEach
    void setup() {
        jdbi = Jdbi.create(postgreSQLContainer.getJdbcUrl(), postgreSQLContainer.getUsername(), postgreSQLContainer.getPassword());
        jsonSerializer = new Jackson3JSONSerializer(EssentialsObjectMappers.createJackson3ObjectMapper());
        jdbi.useHandle(handle -> {
            handle.execute("DROP TABLE IF EXISTS table1");
            handle.execute("DROP TABLE IF EXISTS table2");
            handle.execute("CREATE TABLE table1 (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, column1 TEXT, column2 TEXT)");
            handle.execute("CREATE TABLE table2 (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, column3 TEXT, column4 TEXT)");
            ListenNotify.addChangeNotificationTriggerToTable(handle, TABLE_1, List.of(ListenNotify.SqlOperation.INSERT), "id", "column1", "column2");
            ListenNotify.addChangeNotificationTriggerToTable(handle, TABLE_2, List.of(ListenNotify.SqlOperation.INSERT), "id", "column3", "column4");
        });
        received = new CopyOnWriteArrayList<>();
        eventBus = new LocalEventBus("Notification", 3, (consumer, notification, e) -> {
            throw new RuntimeException(e);
        });
        eventBus.addSyncSubscriber(received::add);
    }

    @AfterEach
    void cleanup() {
        if (listener != null) {
            listener.stop();
            listener.close();
        }
    }

    // -------------------------------------------------------------------------------------------------------------
    // LN-6
    // -------------------------------------------------------------------------------------------------------------

    /**
     * LN-6: {@code LISTEN Table1} is an unquoted identifier, so PostgreSQL listens on {@code table1}, while the trigger's
     * {@code pg_notify('Table1', ...)} is a case-sensitive string, and the payload type was looked up by the name as
     * registered. A mixed-case table name therefore never delivered a single notification.
     */
    @Test
    void a_mixed_case_table_name_delivers_its_notifications() {
        jdbi.useHandle(handle -> ListenNotify.addChangeNotificationTriggerToTable(handle, "Table1", List.of(ListenNotify.SqlOperation.INSERT), "id", "column1", "column2"));
        listener = new MultiTableChangeListener<>(jdbi, Duration.ofMillis(50), jsonSerializer, eventBus, true);
        listener.start();
        listener.listenToNotificationsFor("Table1", Table1Notification.class);

        insertInto(TABLE_1);

        Awaitility.waitAtMost(Duration.ofSeconds(5))
                  .untilAsserted(() -> assertThat(received).hasSize(1).first().isInstanceOf(Table1Notification.class));
    }

    @Test
    void the_channel_name_is_lower_cased() {
        assertThat(ListenNotify.resolveTableChangeChannelName("Orders")).isEqualTo("orders");
        assertThat(ListenNotify.resolveTableChangeChannelName("orders")).isEqualTo("orders");
    }

    // -------------------------------------------------------------------------------------------------------------
    // LN-5 / N-6
    // -------------------------------------------------------------------------------------------------------------

    /**
     * N-6: {@code NotificationFilterChain.extractDuplicationKey} throws on a payload that is not JSON. The poll loop
     * caught it, closed the connection and dropped the whole poll batch - including every table change that arrived
     * with it. A duplication filter is always registered when the PostgreSQL queue is used.
     */
    @Test
    void a_non_json_notification_does_not_drop_the_rest_of_the_poll_batch() {
        listener = new MultiTableChangeListener<>(jdbi, Duration.ofMillis(50), jsonSerializer, eventBus, true);
        listener.addDuplicationFilterAsLast(new NotificationDuplicationFilter.TableNameDuplicationFilter());
        listener.start();
        listener.listenToNotificationsFor(TABLE_1, Table1Notification.class);

        // Same transaction, so both arrive in the same poll batch
        jdbi.useTransaction(handle -> {
            handle.execute("SELECT pg_notify('table1', 'this is not JSON')");
            handle.execute("INSERT INTO table1 (column1, column2) VALUES ('a', 'b')");
        });

        Awaitility.waitAtMost(Duration.ofSeconds(5))
                  .untilAsserted(() -> assertThat(received).hasSize(1).first().isInstanceOf(Table1Notification.class));
    }

    /**
     * LN-5: duplicates were detected across every channel in a poll batch, so two notifications from different tables
     * that happened to produce the same duplication key collapsed into one.
     */
    @Test
    void duplicates_are_detected_per_channel_not_across_channels() {
        listener = new MultiTableChangeListener<>(jdbi, Duration.ofMillis(50), jsonSerializer, eventBus, true);
        listener.addDuplicationFilterAsLast(new IdDuplicationFilter());
        listener.start();
        listener.listenToNotificationsFor(TABLE_1, Table1Notification.class);
        listener.listenToNotificationsFor(TABLE_2, Table2Notification.class);

        // Both rows get id 1, so both notifications carry the same duplication key - but on different channels
        jdbi.useTransaction(handle -> {
            handle.execute("INSERT INTO table1 (column1, column2) VALUES ('a', 'b')");
            handle.execute("INSERT INTO table2 (column3, column4) VALUES ('c', 'd')");
        });

        Awaitility.waitAtMost(Duration.ofSeconds(5))
                  .untilAsserted(() -> assertThat(received).hasSize(2));
        assertThat(received).hasAtLeastOneElementOfType(Table1Notification.class)
                            .hasAtLeastOneElementOfType(Table2Notification.class);
    }

    @Test
    void duplicates_on_the_same_channel_are_still_filtered() {
        listener = new MultiTableChangeListener<>(jdbi, Duration.ofMillis(50), jsonSerializer, eventBus, true);
        listener.addDuplicationFilterAsLast(new NotificationDuplicationFilter.TableNameDuplicationFilter());
        listener.start();
        listener.listenToNotificationsFor(TABLE_1, Table1Notification.class);

        jdbi.useTransaction(handle -> {
            for (var i = 0; i < 10; i++) {
                handle.execute("INSERT INTO table1 (column1, column2) VALUES ('a', 'b')");
            }
        });

        Awaitility.waitAtMost(Duration.ofSeconds(5))
                  .untilAsserted(() -> assertThat(received).hasSize(1));
    }

    // -------------------------------------------------------------------------------------------------------------
    // Helpers
    // -------------------------------------------------------------------------------------------------------------

    private void insertInto(String table) {
        jdbi.useHandle(handle -> {
            if (table.equals(TABLE_1)) {
                handle.execute("INSERT INTO table1 (column1, column2) VALUES ('a', 'b')");
            } else {
                handle.execute("INSERT INTO table2 (column3, column4) VALUES ('c', 'd')");
            }
        });
    }

    private static class IdDuplicationFilter implements NotificationDuplicationFilter {
        @Override
        public Optional<String> extractDuplicationKey(JsonNode notificationParameterJson) {
            return Optional.ofNullable(notificationParameterJson.has("id") ? notificationParameterJson.get("id").asString() : null);
        }
    }

    static class Table2Notification extends TestTableNotification {
        @JsonProperty("column3")
        private String column3;
        @JsonProperty("column4")
        private String column4;
    }
}
